export const modeById = (id: unknown) => MODES.find((mode) => mode.id === id);
export function favoriteIds(value: unknown): string[] {
  return Array.isArray(value)
    ? [...new Set(value.filter((id): id is string => typeof id === 'string' && !!modeById(id)))].slice(
        0,
        MODES.length,
      )
    : [];
}
export function findModes(query: string, category = 'All', favorites?: string[]) {
  const words = query.toLocaleLowerCase().trim().split(/\s+/).filter(Boolean);
  return MODES.filter(
    (mode) =>
      (category === 'All' || mode.category === category) &&
      (!favorites || favorites.includes(mode.id)) &&
      words.every((word) =>
        `${mode.name} ${mode.description} ${mode.highlights.join(' ')} ${mode.category}`
          .toLocaleLowerCase()
          .includes(word),
      ),
  );
}
